class DB:
    def __init__(self):
        self.pg = bool(DATABASE_URL)
        if self.pg:
            try:
                import psycopg
                from psycopg.rows import dict_row
            except ImportError as exc:
                raise RuntimeError("PostgreSQL driver missing: install psycopg[binary]") from exc
            self.conn = psycopg.connect(DATABASE_URL, row_factory=dict_row, autocommit=True)
        else:
            self.conn = sqlite3.connect(DB_PATH, timeout=10, isolation_level=None)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys=ON")
            self.conn.execute("PRAGMA busy_timeout=10000")

    def query(self, sql, values=()):
        if self.pg:
            sql = sql.replace("?", "%s")
        return self.conn.execute(sql, tuple(values))

    def all(self, sql, values=()):
        return [dict(r) for r in self.query(sql, values).fetchall()]

    def one(self, sql, values=()):
        r = self.query(sql, values).fetchone()
        return dict(r) if r is not None else None

    def commit(self):
        self.conn.commit()

    def close(self):
        self.conn.close()

    def __enter__(self):
        return self

    def __exit__(self, typ, val, trace):
        if typ is None:
            self.commit()
        else:
            self.conn.rollback()
        self.close()


def init_db():
    key_type = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if DATABASE_URL else "INTEGER PRIMARY KEY AUTOINCREMENT"
    with DB() as db:
        if not DATABASE_URL:
            db.query("PRAGMA journal_mode=WAL")
        db.query(f"""CREATE TABLE IF NOT EXISTS users (
            id {key_type}, handle TEXT NOT NULL UNIQUE, pass_hash TEXT NOT NULL,
            salt TEXT NOT NULL, created_at BIGINT NOT NULL)""")
        db.query("""CREATE TABLE IF NOT EXISTS sessions (
            token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
            csrf TEXT NOT NULL, expires_at BIGINT NOT NULL)""")
        db.query(f"""CREATE TABLE IF NOT EXISTS posts (
            id {key_type}, user_id BIGINT NOT NULL REFERENCES users(id),
            kind TEXT NOT NULL CHECK(kind IN ('ride','package')),
            title TEXT NOT NULL, start_name TEXT NOT NULL, end_name TEXT NOT NULL,
            start_lat REAL NOT NULL, start_lon REAL NOT NULL,
            end_lat REAL NOT NULL, end_lon REAL NOT NULL,
            departure BIGINT NOT NULL, capacity_kg REAL NOT NULL,
            length_cm REAL NOT NULL, width_cm REAL NOT NULL, height_cm REAL NOT NULL,
            max_detour_km REAL NOT NULL, price REAL NOT NULL,
            vehicle TEXT NOT NULL, details TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'active', created_at BIGINT NOT NULL,
            expires_at BIGINT NOT NULL)""")
        db.query(f"""CREATE TABLE IF NOT EXISTS offers (
            id {key_type}, post_id BIGINT NOT NULL REFERENCES posts(id),
            author_id BIGINT NOT NULL REFERENCES users(id),
            message TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
            created_at BIGINT NOT NULL,
            UNIQUE(post_id, author_id))""")
        db.query(f"""CREATE TABLE IF NOT EXISTS messages (
            id {key_type}, offer_id BIGINT NOT NULL REFERENCES offers(id),
            sender_id BIGINT NOT NULL REFERENCES users(id),
            body TEXT NOT NULL, created_at BIGINT NOT NULL)""")
        db.query(f"""CREATE TABLE IF NOT EXISTS reports (
            id {key_type}, post_id BIGINT NOT NULL REFERENCES posts(id),
            user_id BIGINT NOT NULL REFERENCES users(id),
            reason TEXT NOT NULL, created_at BIGINT NOT NULL,
            UNIQUE(post_id,user_id))""")
        db.query("""CREATE TABLE IF NOT EXISTS limits (
            key TEXT PRIMARY KEY, count BIGINT NOT NULL, reset_at BIGINT NOT NULL)""")
        db.query("CREATE INDEX IF NOT EXISTS idx_posts_kind_active ON posts(kind, status, departure)")
        db.query("CREATE INDEX IF NOT EXISTS idx_offers_parties ON offers(post_id,author_id)")


def now():
    return int(time.time())


def pbkdf(password, salt):
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), 260_000).hex()


def hash_token(value):
    return hashlib.sha256(value.encode()).hexdigest()


def rate_limit(db, key, limit=20, period=3600):
    current = now()
    row = db.one("SELECT count,reset_at FROM limits WHERE key=?", (key,))
    if row and row["reset_at"] > current:
        if row["count"] >= limit:
            raise APIError(429, "Muitas tentativas. Tente mais tarde.")
        db.query("UPDATE limits SET count=count+1 WHERE key=?", (key,))
    else:
        db.query("""INSERT INTO limits(key,count,reset_at) VALUES(?,1,?)
                    ON CONFLICT(key) DO UPDATE SET count=1,reset_at=excluded.reset_at""", (key, current+period))


def text(value, name, minlen=1, maxlen=160):
    if not isinstance(value, str) or not minlen <= len(value.strip()) <= maxlen:
        raise APIError(400, f"{name}: tamanho inválido (mín. {minlen}, máx. {maxlen}).")
    # Never trust user-provided HTML; front-end inserts via textContent.
    if any(ord(c) < 32 and c not in "\n\t" for c in value):
        raise APIError(400, f"{name}: caracteres inválidos.")
    return value.strip()


def number(value, name, low, high):
    if type(value) not in (int, float) or not math.isfinite(value) or not low <= value <= high:
        raise APIError(400, f"{name}: valor fora dos limites.")
    return float(value)


def coordinates(d, prefix):
    lat = number(d.get(prefix+"_lat"), prefix+"_lat", -90, 90)
    lon = number(d.get(prefix+"_lon"), prefix+"_lon", -180, 180)
    # Intentionally round location in public posts to approximately 1km,
    # preventing disclosure of a user's actual home or live GPS location.
    return round(lat, 2), round(lon, 2)


def km(a, b):
    p1, l1, p2, l2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    x = math.sin((p2-p1)/2)**2 + math.cos(p1)*math.cos(p2)*math.sin((l2-l1)/2)**2
    return 12742 * math.asin(min(1, math.sqrt(x)))


def matching(ride, pack):
    """Candidate pre-filter only; never claims driving duration or road detour."""
    if ride["kind"] != "ride" or pack["kind"] != "package":
        return None
    if float(pack["capacity_kg"]) > float(ride["capacity_kg"]):
        return None
    # Fit by checking all axis-aligned box orientations. No claimed load certification.
    try:
        car = sorted(float(ride[k]) for k in ("length_cm", "width_cm", "height_cm"))
        parcel = sorted(float(pack[k]) for k in ("length_cm", "width_cm", "height_cm"))
        if any(v <= 0 for v in car + parcel) or any(p > c for p,c in zip(parcel,car)):
            return None
    except (KeyError,TypeError,ValueError):
        return None
    if abs(int(ride["departure"]) - int(pack["departure"])) > 6*3600:
        return None
    s = ride["start_lat"], ride["start_lon"]
    e = ride["end_lat"], ride["end_lon"]
    a = pack["start_lat"], pack["start_lon"]
    b = pack["end_lat"], pack["end_lon"]
    base = km(s, e)
    if base < 1:
        return None
    # Progress along the direct line: very conservative first-pass gate.
    def progress(point):
        dx, dy = e[0]-s[0], (e[1]-s[1])*math.cos(math.radians((s[0]+e[0])/2))
        px, py = point[0]-s[0], (point[1]-s[1])*math.cos(math.radians((s[0]+e[0])/2))
        d = dx*dx+dy*dy
        return (px*dx+py*dy)/d if d > 0 else 0
    pa, pb = progress(a), progress(b)
    if not (-0.10 <= pa <= 1.10 and -0.10 <= pb <= 1.10 and pa <= pb):
        return None
    # Lower bound only, NOT actual driving detour.
    extra_lower = max(0, km(s, a)+km(a, b)+km(b, e)-base)
    if extra_lower > ride["max_detour_km"]:
        return None
    return {"lower_bound_extra_km": round(extra_lower, 1),
            "road_route_confirmed": False, "estimated_minutes": None,
            "reason": "Candidato geométrico. Confirmar rota e tempo em um navegador rodoviário antes de aceitar."}


class APIError(Exception):
    def __init__(self, status, message):
        self.status, self.message = status, message
        super().__init__(message)


class Handler(BaseHTTPRequestHandler):
    server_version = "CONEXA/0.1"

    def log_message(self, fmt, *args):
        # Do not log request query strings, location, messages, or credentials.
        sys.stderr.write("CONEXA %s status_event\n" % datetime.now(timezone.utc).isoformat())

    def headers_common(self):
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("X-Frame-Options", "DENY")
        self.send_header("Cache-Control", "no-store")
        self.send_header("Permissions-Policy", "geolocation=(self), microphone=()")
        self.send_header("Content-Security-Policy", "default-src 'self'; script-src 'self' https://unpkg.com; style-src 'self' https://unpkg.com; img-src 'self' data: https://tile.openstreetmap.org https://unpkg.com; connect-src 'self'; font-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'")

    def response(self, status, obj, cookie=None):
        payload = json.dumps(obj, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        if cookie:
            self.send_header("Set-Cookie", cookie)
        self.headers_common()
        self.end_headers()
        self.wfile.write(payload)

    def serve_static(self, name):
        allowed = {"/": (ROOT/"static"/"index.html", "text/html; charset=utf-8"),
                   "/static/style.css": (ROOT/"static"/"style.css", "text/css; charset=utf-8"),
                   "/static/app.js": (ROOT/"static"/"app.js", "text/javascript; charset=utf-8")}
        if name not in allowed:
            raise APIError(404, "Não encontrado.")
        path, mime = allowed[name]
        body = path.read_bytes()
        self.send_response(200)
        self.send_header("Content-Type", mime)
        self.send_header("Content-Length", str(len(body)))
        self.headers_common()
        self.end_headers()
        self.wfile.write(body)

    def user(self, db):
        cookie = SimpleCookie()
        try:
            cookie.load(self.headers.get("Cookie", ""))
            token = cookie.get("conexa_session")
        except Exception:
            return None
        if not token:
            return None
        return db.one("""SELECT users.id,users.handle,sessions.csrf,sessions.token_hash
                         FROM sessions JOIN users ON users.id=sessions.user_id
                         WHERE sessions.token_hash=? AND sessions.expires_at>?""",
                      (hash_token(token.value), now()))

    def require_auth(self, db):
        u = self.user(db)
        if not u:
            raise APIError(401, "Entre na sua conta para continuar.")
        if not hmac.compare_digest(self.headers.get("X-CSRF-Token", ""), u["csrf"]):
            raise APIError(403, "Sessão de proteção inválida. Recarregue a página.")
        return u

    def check_origin(self):
        orig = self.headers.get("Origin")
        if orig:
            source = urlparse(orig)
            if source.netloc != self.headers.get("Host") or source.scheme not in ("https", "http"):
                raise APIError(403, "Origem não autorizada.")

    def body(self):
        length = self.headers.get("Content-Length", "")
        if not length.isdigit() or int(length) > MAX_BODY:
            raise APIError(413, "Pedido muito grande ou inválido.")
        if "application/json" not in self.headers.get("Content-Type", ""):
            raise APIError(415, "Envie JSON.")
        try:
            result = json.loads(self.rfile.read(int(length)))
        except (UnicodeDecodeError, ValueError):
            raise APIError(400, "JSON inválido.")
        if not isinstance(result, dict):
            raise APIError(400, "Objeto JSON necessário.")
        return result

    def do_GET(self):
        try:
            path = urlparse(self.path).path
            if not path.startswith("/api/"):
                return self.serve_static(path)
            with DB() as db:
                if path == "/api/health":
                    return self.response(200, {"ok": True,"mode":"beta",
                        "persistence":"postgresql" if DATABASE_URL else "sqlite_local",
                        "durable_public_storage":bool(DATABASE_URL),
                        "real_road_routing":False,"gps":"browser_opt_in"})
                if path == "/api/me":
                    u = self.user(db)
                    return self.response(200, {"user":{"id":u["id"],"handle":u["handle"]} if u else None,
                                                "csrf":u["csrf"] if u else None})
                if path == "/api/posts":
                    query = parse_qs(urlparse(self.path).query)
                    kind = query.get("kind", [""])[0]
                    if kind not in ("", "ride", "package"):
                        raise APIError(400, "Tipo inválido")
                    where = "AND p.kind=?" if kind else ""
                    records = db.all("""SELECT p.*,u.handle FROM posts p JOIN users u ON u.id=p.user_id
                                    WHERE p.status='active' AND p.departure>? """+where+
                                    " ORDER BY p.created_at DESC LIMIT ?",
                                    ((now()-1800,kind,MAX_LIST) if kind else (now()-1800,MAX_LIST)))
                    return self.response(200, {"posts": [public_post(x) for x in records]})
                if path == "/api/my-posts":
                    u=self.user(db)
                    if not u: raise APIError(401, "Entre na sua conta.")
                    records=db.all("""SELECT p.*,u.handle FROM posts p JOIN users u ON u.id=p.user_id
                                      WHERE p.user_id=? ORDER BY p.created_at DESC LIMIT 80""", (u["id"],))
                    return self.response(200,{"posts":[public_post(x) for x in records]})
                if path == "/api/offers":
                    u=self.user(db)
                    if not u: raise APIError(401,"Entre na sua conta.")
                    records=db.all("""SELECT o.*,p.title,p.kind,p.user_id AS owner_id,
                                       sender.handle AS from_handle,owner.handle AS to_handle
                                       FROM offers o JOIN posts p ON p.id=o.post_id
                                       JOIN users sender ON sender.id=o.author_id
                                       JOIN users owner ON owner.id=p.user_id
                                       WHERE o.author_id=? OR p.user_id=?
                                       ORDER BY o.created_at DESC LIMIT 80""",(u["id"],u["id"]))
                    return self.response(200,{"offers":records})
                if path == "/api/messages":
                    u=self.user(db)
                    if not u: raise APIError(401,"Entre na sua conta.")
                    q=parse_qs(urlparse(self.path).query)
                    oid=safe_int(q.get("offer_id",[None])[0],"offer_id")
                    offer=db.one("""SELECT o.author_id,p.user_id AS owner_id
                                    FROM offers o JOIN posts p ON p.id=o.post_id WHERE o.id=?""",(oid,))
                    if not offer or u["id"] not in (offer["author_id"],offer["owner_id"]):
                        raise APIError(404,"Conversa indisponível.")
                    records=db.all("""SELECT m.id,m.sender_id,u.handle,m.body,m.created_at
                                      FROM messages m JOIN users u ON m.sender_id=u.id
                                      WHERE m.offer_id=? ORDER BY m.id ASC LIMIT 100""",(oid,))
                    return self.response(200,{"messages":records})
            raise APIError(404,"Rota inexistente.")
        except APIError as exc:
            self.response(exc.status, {"error":exc.message})
        except (OSError, ValueError, sqlite3.Error) as exc:
            self.internal_error(exc)
        except Exception as exc:
            self.internal_error(exc)

    def do_POST(self):
        try:
            self.check_origin()
            path = urlparse(self.path).path
            data = self.body()
            with DB() as db:
                remote = self.client_address[0]
                if path == "/api/register":
                    rate_limit(db, "signup:"+remote, 8, 3600)
                    handle = text(data.get("handle"), "Usuário",3,24).lower()
                    if not HANDLE.fullmatch(handle): raise APIError(400,"Usuário: use letras, números ou _.")
                    pwd=data.get("password")
                    if not isinstance(pwd,str) or not 12<=len(pwd)<=128:
                        raise APIError(400,"Senha: utilize entre 12 e 128 caracteres.")
                    if data.get("adult") is not True or data.get("terms") is not True:
                        raise APIError(400,"É necessário ser maior de 18 anos e aceitar as condições do piloto.")
                    if db.one("SELECT id FROM users WHERE handle=?",(handle,)):
                        raise APIError(409,"Nome de usuário indisponível.")
                    salt=secrets.token_hex(16)
                    user=db.one("""INSERT INTO users(handle,pass_hash,salt,created_at)
                               VALUES(?,?,?,?) RETURNING id,handle""",(handle,pbkdf(pwd,salt),salt,now()))
                    return self.login_session(db, user)
                if path == "/api/login":
                    rate_limit(db, "login:"+remote, 25, 3600)
                    handle=data.get("handle","")
                    password=data.get("password","")
                    if not isinstance(handle,str) or not isinstance(password,str):
                        raise APIError(401,"Credenciais inválidas.")
                    u=db.one("SELECT id,handle,pass_hash,salt FROM users WHERE handle=?",(handle.lower(),))
                    # Constant-time fallback for nonexistent user.
                    salt=u["salt"] if u else "00"*16
                    digest=pbkdf(password[:128],salt)
                    if not u or not hmac.compare_digest(digest,u["pass_hash"]):
                        raise APIError(401,"Credenciais inválidas.")
                    return self.login_session(db,u)
                if path == "/api/logout":
                    u=self.require_auth(db)
                    db.query("DELETE FROM sessions WHERE token_hash=?",(u["token_hash"],))
                    return self.response(200,{"ok":True}, cookie=self.cookie("", maxage=0))
                u=self.require_auth(db)
                if path == "/api/posts":
                    rate_limit(db,"post:"+str(u["id"]),5,24*3600)
                    kind=data.get("kind")
                    if kind not in KINDS: raise APIError(400,"Tipo de publicação inválido.")
                    title=text(data.get("title"),"Título",8,90)
                    start_name=text(data.get("start_name"),"Origem",2,70)
                    end_name=text(data.get("end_name"),"Destino",2,70)
                    start_lat,start_lon=coordinates(data,"start")
                    end_lat,end_lon=coordinates(data,"end")
                    if km((start_lat,start_lon),(end_lat,end_lon)) < 1:
                        raise APIError(400,"Origem e destino precisam ser diferentes.")
                    length_cm=number(data.get("length_cm"),"Comprimento (cm)",1,1000)
                    width_cm=number(data.get("width_cm"),"Largura (cm)",1,1000)
                    height_cm=number(data.get("height_cm"),"Altura (cm)",1,1000)
                    departure=data.get("departure")
                    if type(departure) is not int or not now()-1800 <= departure <= now()+30*24*3600:
                        raise APIError(400,"Partida: horário inválido ou fora dos próximos 30 dias.")
                    capacity=number(data.get("capacity_kg"),"Peso/capacidade kg",0.1,2500)
                    detour=number(data.get("max_detour_km",0),"Desvio máximo km",0,100) if kind=="ride" else 0
                    price=number(data.get("price",0),"Valor R$",0,100000)
                    vehicle=text(data.get("vehicle","Não informado") if kind=="ride" else "Encomenda","Veículo",1,60)
                    details=text(data.get("details","Sem observações") or "Sem observações","Observações",1,400)
                    row=db.one("""INSERT INTO posts(user_id,kind,title,start_name,end_name,start_lat,start_lon,
                                   end_lat,end_lon,departure,capacity_kg,length_cm,width_cm,height_cm,max_detour_km,price,vehicle,details,
                                   status,created_at,expires_at)
                                   VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,'active',?,?) RETURNING id""",
                                   (u["id"],kind,title,start_name,end_name,start_lat,start_lon,end_lat,end_lon,
                                    departure,capacity,length_cm,width_cm,height_cm,detour,price,vehicle,details,now(),departure+24*3600))
                    return self.response(201,{"ok":True,"id":row["id"]})
                if path == "/api/close":
                    pid=safe_int(data.get("post_id"),"post_id")
                    post=db.one("SELECT user_id,status FROM posts WHERE id=?",(pid,))
                    if not post or post["user_id"] != u["id"]:
                        raise APIError(404,"Anúncio não encontrado.")
                    db.query("UPDATE posts SET status='closed' WHERE id=?",(pid,))
                    return self.response(200,{"ok":True})
                if path == "/api/matches":
                    rid=safe_int(data.get("ride_id"),"ride_id")
                    ride=db.one("SELECT * FROM posts WHERE id=? AND user_id=? AND kind='ride' AND status='active'",
                                (rid,u["id"]))
                    if not ride: raise APIError(404,"Viagem ativa não encontrada.")
                    posts=db.all("""SELECT p.*,u.handle FROM posts p JOIN users u ON u.id=p.user_id
                                    WHERE p.kind='package' AND p.status='active' AND
                                    p.user_id<>? AND p.departure BETWEEN ? AND ? LIMIT 200""",
                                    (u["id"],ride["departure"]-21600,ride["departure"]+21600))
                    out=[]
                    for p in posts:
                        m=matching(ride,p)
                        if m: out.append({"post":public_post(p),"compatibility":m})
                    out.sort(key=lambda v:v["compatibility"]["lower_bound_extra_km"])
                    return self.response(200,{"matches":out[:50],"calculation":"geometric_lower_bound_only"})
                if path == "/api/offers":
                    rate_limit(db,"offer:"+str(u["id"]),25,24*3600)
                    pid=safe_int(data.get("post_id"),"post_id")
                    post=db.one("SELECT * FROM posts WHERE id=? AND status='active' AND departure>?",(pid,now()-1800))
                    if not post or post["user_id"]==u["id"]:
                        raise APIError(400,"Anúncio não disponível para essa proposta.")
                    msg=text(data.get("message"),"Mensagem",10,500)
                    if db.one("SELECT id FROM offers WHERE post_id=? AND author_id=?",(pid,u["id"])):
                        raise APIError(409,"Você já enviou uma proposta para este anúncio.")
                    row=db.one("INSERT INTO offers(post_id,author_id,message,created_at) VALUES(?,?,?,?) RETURNING id",
                               (pid,u["id"],msg,now()))
                    return self.response(201,{"ok":True,"id":row["id"]})
                if path == "/api/respond":
                    oid=safe_int(data.get("offer_id"),"offer_id")
                    status=data.get("status")
                    if status not in ("accepted","rejected"):
                        raise APIError(400,"Resposta inválida.")
                    offer=db.one("""SELECT o.status,o.post_id,p.user_id AS owner_id
                                    FROM offers o JOIN posts p ON p.id=o.post_id WHERE o.id=?""",(oid,))
                    if not offer or offer["owner_id"]!=u["id"] or offer["status"]!="pending":
                        raise APIError(403,"Proposta indisponível ou já respondida.")
                    db.query("UPDATE offers SET status=? WHERE id=?",(status,oid))
                    # For a private pilot do not auto-close: owner can accept several candidates
                    # but must manually agree logistics and payment details.
                    return self.response(200,{"ok":True})
                if path == "/api/messages":
                    oid=safe_int(data.get("offer_id"),"offer_id")
                    offer=db.one("""SELECT o.author_id,p.user_id AS owner_id
                                    FROM offers o JOIN posts p ON p.id=o.post_id WHERE o.id=?""",(oid,))
                    if not offer or u["id"] not in (offer["author_id"],offer["owner_id"]):
                        raise APIError(404,"Conversa indisponível.")
                    rate_limit(db,"message:"+str(u["id"]),80,3600)
                    body=text(data.get("body"),"Mensagem",1,600)
                    db.query("INSERT INTO messages(offer_id,sender_id,body,created_at) VALUES(?,?,?,?)",
                             (oid,u["id"],body,now()))
                    return self.response(201,{"ok":True})
                if path == "/api/report":
                    pid=safe_int(data.get("post_id"),"post_id")
                    reason=text(data.get("reason"),"Motivo",5,200)
                    if not db.one("SELECT id FROM posts WHERE id=?",(pid,)):
                        raise APIError(404,"Anúncio não encontrado.")
                    if db.one("SELECT id FROM reports WHERE post_id=? AND user_id=?",(pid,u["id"])):
                        raise APIError(409,"Denúncia já registrada.")
                    db.query("INSERT INTO reports(post_id,user_id,reason,created_at) VALUES(?,?,?,?)",
                             (pid,u["id"],reason,now()))
                    return self.response(201,{"ok":True})
            raise APIError(404,"Rota inexistente.")
        except APIError as exc:
            self.response(exc.status,{"error":exc.message})
        except Exception as exc:
            self.internal_error(exc)

    def login_session(self, db, user):
        token=secrets.token_urlsafe(40)
        csrf=secrets.token_urlsafe(32)
        db.query("INSERT INTO sessions(token_hash,user_id,csrf,expires_at) VALUES(?,?,?,?)",
                 (hash_token(token),user["id"],csrf,now()+SESSION_AGE))
        return self.response(200,{"ok":True,"user":{"id":user["id"],"handle":user["handle"]},"csrf":csrf},
                             cookie=self.cookie(token))

    def cookie(self, token, maxage=SESSION_AGE):
        suffix="; Secure" if IS_PROD else ""
        return f"conexa_session={token}; HttpOnly; SameSite=Lax; Path=/; Max-Age={maxage}{suffix}"

    def internal_error(self, exc):
        sys.stderr.write("CONEXA API internal error: "+type(exc).__name__+"\n")
        try: self.response(500,{"error":"Erro interno; tente novamente."})
        except OSError: pass


def safe_int(v, label):
    if type(v) is int and 0 < v < 2**63:
        return v
    if isinstance(v,str) and v.isdecimal() and len(v)<=18 and int(v)>0:
        return int(v)
    raise APIError(400, f"{label}: identificador inválido.")


